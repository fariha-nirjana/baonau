/** Fills {owner} everywhere in a set of overrides. */
function withOwner<T>(over: Partial2<T>, owner: string): Partial2<T> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(over as Record<string, unknown>)) {
    out[k] = typeof v === "string" ? v.replace(/\{owner\}/g, owner) : withOwner(v as Partial2<unknown>, owner);
  }
  return out as Partial2<T>;
}

const TABLE: Record<Language, Strings> = { en, bn, zh: merge<Strings>(en, zh) };

/** The name the investor gave in the setup; until then, the demo persona from brand.ts. */
let givenName: string | null = null;

export function setOwnerName(name: string | null | undefined) {
  givenName = name?.trim() || null;
}

export function ownerName(language: Language): string {
  return givenName ?? (language === "bn" ? BRAND.ownerBn : BRAND.owner);
}

const contactCache = new Map<string, Strings>();

function contactTable(language: Language): Strings {
  const name = ownerName(language);
  const key = `${language}|${name}`;
  let table = contactCache.get(key);
  if (!table) {
    table =
      language === "bn"
        ? merge<Strings>(bn, withOwner(bnContact, name))
        : language === "zh"
          ? // the contact's own lines win over the owner's Chinese; English fills any gap
            merge<Strings>(merge<Strings>(merge<Strings>(en, withOwner(enContact, name)), zh), withOwner(zhContact, name))
          : merge<Strings>(en, withOwner(enContact, name));
    contactCache.set(key, table);
  }
  return table;
}

/** Screen text for a language, from the owner's side or the trusted contact's. */
export function strings(language: Language, role: "owner" | "guardian" = "owner"): Strings {
  return role === "guardian" ? contactTable(language) : TABLE[language];
}

/** Fills `{key}` placeholders. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** The locale used for dates and times in each language. */
export const LOCALE: Record<Language, string> = { en: "en-GB", bn: "bn-BD-u-nu-latn", zh: "zh-CN" };

/** Clock times are 24-hour with Latin digits in every language, so amounts and times read the same everywhere. */
export function clock(iso: string): string {
  return new Date(iso).toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit" });
}

/** Seconds left as "1 min 20 s" in the screen's language, with Latin digits. */
export function formatLeft(seconds: number, t: Strings): string {
  if (seconds < 90) return fill(t.time.s, { s: seconds });
  if (seconds < 5400) return seconds % 60 === 0 ? fill(t.signed.minutes, { n: seconds / 60 }) : fill(t.time.ms, { m: Math.floor(seconds / 60), s: seconds % 60 });
  if (seconds < 172800) return fill(t.time.hm, { h: Math.floor(seconds / 3600), m: Math.floor((seconds % 3600) / 60) });
  return fill(t.time.d, { d: Math.floor(seconds / 86400) });
}
