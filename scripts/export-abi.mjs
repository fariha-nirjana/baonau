// Copies the compiled contract ABIs into the app as typed constants.
// Run after `forge build`:  node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const abiOf = (name) =>
  JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8")).abi;

const exports = {
  policyVaultAbi: "PolicyVault",
  priceOracleAbi: "PriceOracle",
  mockExchangeAbi: "MockExchange",
  mockAssetAbi: "MockAsset",
  testUsdAbi: "TestUSD",
};

const body = [
  "// Generated by scripts/export-abi.mjs. Do not edit by hand.",
  ...Object.entries(exports).map(
    ([name, contract]) => `export const ${name} = ${JSON.stringify(abiOf(contract), null, 2)} as const;`,
  ),
  "",
].join("\n\n");

writeFileSync(join(root, "app/lib/abi.ts"), body);
console.log("Wrote app/lib/abi.ts");
